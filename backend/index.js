import "dotenv/config";
import express from "express";
import cors from "cors";
import { requireAuth } from "./middleware/auth.js";
import auth from "./routes/auth.js";
import bills from "./routes/bills.js";
import indoor from "./routes/indoor.js";
import medicines from "./routes/medicines.js";
import reports from "./routes/reports.js";
import analyze from "./routes/analyze.js";
import sync from "./routes/sync.js";
if (!process.env.JWT_SECRET) throw new Error("JWT_SECRET missing");
const app = express();
app.use(cors()); app.use(express.json({ limit: "2mb" }));
app.get("/health", (_, res) => res.json({ ok: true }));
app.use("/api/auth", auth);
app.use("/api", requireAuth);
app.use("/api/bills", bills);
app.use("/api/common-medicines", medicines);
app.use("/api", indoor, reports, analyze, sync);
app.use((err, req, res, _next) => { console.error(err); res.status(500).json({ error: "Server error" }); });
const port = process.env.PORT || 4000;
app.listen(port, () => console.log(`Omshree Medicals API on :${port}`));
